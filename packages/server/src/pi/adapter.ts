import { spawn, type ChildProcess } from "node:child_process";
import { EventEmitter } from "node:events";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import type {
  ExtensionUiResponse,
  Model,
  RpcCommand,
  RpcEvent,
  RpcRecord,
  RpcResponse,
  SessionState,
  SessionStats,
  ThinkingLevel,
} from "@pi-gui/protocol";
import { JsonlSplitter, encodeJsonl } from "./jsonl.ts";

export interface PiSpawnOptions {
  cwd: string;
  /** command + leading args, e.g. ["node", "/path/cli.js"]; defaults to the pinned pi */
  piCommand?: string[];
  args?: string[];
  env?: Record<string, string>;
  requestTimeoutMs?: number;
}

export interface PiExitInfo {
  code: number | null;
  signal: string | null;
  stderrTail: string;
  /** true when we asked it to stop */
  expected: boolean;
}

/**
 * Bootstrap pi loads first. It moves GUI-private values out of process.env *before* pi starts,
 * so nothing pi spawns (bash tool, agent commands) inherits them:
 *  - ELECTRON_RUN_AS_NODE: needed to start Electron's binary as Node, harmful to Electron apps run by the agent
 *  - PI_GUI_TOKEN: GUI access token; kept in globalThis.__piGui for our gui-bridge extension only
 */
export const PI_BOOT_SOURCE = `// generated by pi-gui — do not edit
import { pathToFileURL } from "node:url";
const cli = process.argv[2];
globalThis.__piGui = Object.freeze({
  url: process.env.PI_GUI_URL,
  token: process.env.PI_GUI_TOKEN,
  sessionId: process.env.PI_GUI_SESSION_ID,
});
delete process.env.ELECTRON_RUN_AS_NODE;
delete process.env.PI_GUI_TOKEN;
process.argv.splice(1, 2, cli); // pi sees itself as argv[1], args unchanged
await import(pathToFileURL(cli).href);
`;

export function writePiBoot(dir: string): string {
  const file = join(dir, "pi-boot.mjs");
  mkdirSync(dir, { recursive: true });
  if (!existsSync(file) || readFileSync(file, "utf8") !== PI_BOOT_SOURCE) writeFileSync(file, PI_BOOT_SOURCE);
  return file;
}

/** The pinned pi CLI shipped as a dependency, started through the env-scrubbing bootstrap when `bootDir` is given. */
export function defaultPiCommand(bootDir?: string): string[] {
  const override = process.env.PI_GUI_PI_BIN;
  if (override) return override.split(" ").filter(Boolean);
  // package is ESM-only ("import" condition, no ./package.json export) → resolve the entry, cli.js sits next to it
  const entry = fileURLToPath(import.meta.resolve("@mariozechner/pi-coding-agent"));
  const cli = join(dirname(entry), "cli.js");
  return bootDir ? [process.execPath, writePiBoot(bootDir), cli] : [process.execPath, cli];
}

const STDERR_TAIL = 8 * 1024;

interface Pending {
  resolve: (r: RpcResponse) => void;
  reject: (e: Error) => void;
  timer: NodeJS.Timeout;
}

/**
 * One `pi --mode rpc` child process. Emits:
 *  - "event" (RpcEvent)    every non-response record, incl. extension_ui_request
 *  - "stderr" (string)
 *  - "exit" (PiExitInfo)
 * All pi-specific wire knowledge lives here and in protocol/rpc.ts.
 */
export class PiProcess extends EventEmitter {
  private child?: ChildProcess;
  private pending = new Map<string, Pending>();
  private seq = 0;
  private stderrTail = "";
  private stopping = false;
  private exited?: Promise<PiExitInfo>;

  constructor(readonly opts: PiSpawnOptions) {
    super();
  }

  get pid(): number | undefined {
    return this.child?.pid;
  }
  get running(): boolean {
    return !!this.child && this.child.exitCode === null && this.child.signalCode === null;
  }

  start(): void {
    if (this.child) throw new Error("already started");
    const [cmd, ...pre] = this.opts.piCommand ?? defaultPiCommand();
    const child = spawn(cmd!, [...pre, "--mode", "rpc", ...(this.opts.args ?? [])], {
      cwd: this.opts.cwd,
      env: { ...process.env, ...this.opts.env },
      stdio: ["pipe", "pipe", "pipe"],
      // own process group so stop() can kill pi *and* anything it spawned (bash tool etc.)
      detached: process.platform !== "win32",
    });
    this.child = child;

    const splitter = new JsonlSplitter((line) => this.onLine(line));
    child.stdout!.on("data", (c: Buffer) => splitter.push(c));
    child.stdout!.on("end", () => splitter.end());
    child.stderr!.setEncoding("utf8");
    child.stderr!.on("data", (s: string) => {
      this.stderrTail = (this.stderrTail + s).slice(-STDERR_TAIL);
      this.emit("stderr", s);
    });
    child.stdin!.on("error", () => {}); // EPIPE after crash; surfaced via exit

    this.exited = new Promise((resolve) => {
      const finish = (code: number | null, signal: NodeJS.Signals | null) => {
        const info: PiExitInfo = { code, signal, stderrTail: this.stderrTail, expected: this.stopping };
        for (const [, p] of this.pending) {
          clearTimeout(p.timer);
          p.reject(new Error(`pi exited (code=${code}, signal=${signal})`));
        }
        this.pending.clear();
        this.emit("exit", info);
        resolve(info);
      };
      child.on("exit", finish);
      child.on("error", (err) => {
        this.stderrTail += `\n[spawn error] ${err.message}`;
        if (child.exitCode === null && child.pid === undefined) finish(null, null);
      });
    });
  }

  private onLine(line: string): void {
    let rec: RpcRecord;
    try {
      rec = JSON.parse(line) as RpcRecord;
    } catch {
      this.emit("stderr", `[non-json stdout] ${line}\n`);
      return;
    }
    if (rec.type === "response") {
      const p = rec.id ? this.pending.get(rec.id) : undefined;
      if (p) {
        clearTimeout(p.timer);
        this.pending.delete(rec.id!);
        p.resolve(rec);
      }
      return;
    }
    this.emit("event", rec as RpcEvent);
  }

  private write(obj: unknown): void {
    if (!this.running) throw new Error("pi is not running");
    this.child!.stdin!.write(encodeJsonl(obj));
  }

  /** Send a command, resolve with the response (success or not). Rejects on timeout or exit. */
  send(cmd: RpcCommand, timeoutMs = this.opts.requestTimeoutMs ?? 30_000): Promise<RpcResponse> {
    const id = `g${++this.seq}`;
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => {
        this.pending.delete(id);
        reject(new Error(`pi did not answer ${cmd.type} within ${timeoutMs}ms`));
      }, timeoutMs);
      this.pending.set(id, { resolve, reject, timer });
      try {
        this.write({ ...cmd, id });
      } catch (e) {
        clearTimeout(timer);
        this.pending.delete(id);
        reject(e as Error);
      }
    });
  }

  /** Like send() but throws on success:false and returns data. */
  async call<T = unknown>(cmd: RpcCommand, timeoutMs?: number): Promise<T> {
    const r = await this.send(cmd, timeoutMs);
    if (!r.success) throw new Error(r.error ?? `${cmd.type} failed`);
    return r.data as T;
  }

  respondUi(resp: ExtensionUiResponse): void {
    this.write(resp);
  }

  // ---- typed helpers ----
  prompt(message: string, streamingBehavior?: "steer" | "followUp") {
    return this.call({ type: "prompt", message, ...(streamingBehavior ? { streamingBehavior } : {}) });
  }
  steer(message: string) {
    return this.call({ type: "steer", message });
  }
  followUp(message: string) {
    return this.call({ type: "follow_up", message });
  }
  abort() {
    return this.call({ type: "abort" });
  }
  getState() {
    return this.call<SessionState>({ type: "get_state" });
  }
  getMessages() {
    return this.call<{ messages: unknown[] }>({ type: "get_messages" });
  }
  getModels() {
    return this.call<{ models: Model[] }>({ type: "get_available_models" });
  }
  setModel(provider: string, modelId: string) {
    return this.call<Model>({ type: "set_model", provider, modelId });
  }
  setThinking(level: ThinkingLevel) {
    return this.call({ type: "set_thinking_level", level });
  }
  getStats() {
    return this.call<SessionStats>({ type: "get_session_stats" });
  }

  /** Graceful stop: SIGTERM the process group, SIGKILL after grace period. */
  async stop(graceMs = 3000): Promise<PiExitInfo | undefined> {
    if (!this.child || !this.exited) return undefined;
    this.stopping = true;
    if (this.running) {
      killTree(this.child, "SIGTERM");
      const t = setTimeout(() => this.child && killTree(this.child, "SIGKILL"), graceMs);
      const info = await this.exited;
      clearTimeout(t);
      return info;
    }
    return this.exited;
  }

  /** Immediate SIGKILL of the whole group (abort of last resort, app exit). */
  kill(): void {
    if (this.child && this.running) {
      this.stopping = true;
      killTree(this.child, "SIGKILL");
    }
  }

  waitForExit(): Promise<PiExitInfo> {
    if (!this.exited) throw new Error("not started");
    return this.exited;
  }
}

export function killTree(child: ChildProcess, signal: NodeJS.Signals): void {
  if (!child.pid) return;
  try {
    if (process.platform === "win32") {
      spawn("taskkill", ["/pid", String(child.pid), "/T", "/F"]);
    } else {
      process.kill(-child.pid, signal); // negative pid = process group
    }
  } catch {
    try {
      child.kill(signal);
    } catch {
      /* already gone */
    }
  }
}
